"""
Mostly Significant: the hunch fact-checker.

Someone picks a place and an everyday feeling about the weather ("summers last longer"),
guesses whether it is true, and the app shows what 45 years of NASA data say about it.

How it is run: streamlit run app.py
Reads:  data-generation/data/results/results.csv   the verdict for each place and hunch
        data-generation/data/results/annual.csv    the yearly values behind each verdict
        data-generation/data/results/luck.csv      the shuffle test for each verdict

Nothing is calculated here. Every number on the page is looked up in those three files,
which are generated by the code in data-generation/.
"""
import datetime
import os

import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
import streamlit as st

# The results folder is found from this file's own location, so the app runs from any folder.
RESULTS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                           "data-generation", "data", "results")

# Each measure in the data, worded as the everyday hunch it tests.
HUNCHES = {
    "heatwave_days": "Summers are getting hotter",
    "heatwave_events": "We get more heatwaves than we used to",
    "longest_heatwave": "Heatwaves last longer",
    "first_heatwave_doy": "The first heatwave comes earlier in the year",
    "hottest_day": "The hottest day of the year is getting hotter",
    "warm_nights": "Nights are getting too warm to sleep",
    "summer_length": "Summer lasts longer",
    "autumn_onset_doy": "Autumn arrives later",
    "first_frost_doy": "The first frost comes later",
    "wettest_day": "Downpours are getting heavier",
    "heavy_rain_days": "We get more days of heavy rain",
    "summer_dry_spell": "Summer dry spells are getting longer",
    "winter_rain": "Winters are getting wetter",
    "summer_sunshine": "Summers are getting sunnier",
    "heating_need": "We need less heating than we used to",
}

# The four verdict words in the data: the label and sentence shown for each, the kind of
# box it is drawn in, and its colour on the map. The same colour always means the same thing.
VERDICTS = {
    "real": dict(label="Real trend", box=st.success, colour="#2ecc71",
                 text="The data backs this hunch."),
    "leaning": dict(label="Leaning, not proven", box=st.warning, colour="#f1c40f",
                    text="The data points this way, but luck can't be ruled out yet."),
    "not_backed": dict(label="Not backed up", box=st.info, colour="#95a5a6",
                       text="The data doesn't support this hunch."),
    "opposite": dict(label="The opposite", box=st.error, colour="#e74c3c",
                     text="Surprise: the data shows the reverse is happening."),
}

GUESSES = ["Yes, that's happening", "No, it isn't", "Not sure"]

# What the page says when the guess is compared with the verdict: (guess, verdict) -> sentence.
GUT_CHECK = {
    (GUESSES[0], "real"): "Your gut was right. The data backs you up.",
    (GUESSES[0], "leaning"): "Your gut may be right. The data points your way, but it isn't proven yet.",
    (GUESSES[0], "not_backed"): "Your gut and the data disagree. There is no sign of this in the numbers.",
    (GUESSES[0], "opposite"): "Your gut and the data disagree. It is actually going the other way.",
    (GUESSES[1], "real"): "Your gut and the data disagree. This one is really happening.",
    (GUESSES[1], "leaning"): "You were right to doubt it. It isn't proven, though the data does lean that way.",
    (GUESSES[1], "not_backed"): "Your gut was right. The data doesn't show it.",
    (GUESSES[1], "opposite"): "You were right that it isn't happening. In fact it is going the other way.",
}


@st.cache_data
def load_data():
    """Reads the three results files once and keeps them in memory between clicks."""
    read = lambda name: pd.read_csv(os.path.join(RESULTS_DIR, name), encoding="utf-8")
    return read("results.csv"), read("annual.csv"), read("luck.csv")


def as_date(day_of_year):
    """Turns a day number into a calendar date in words: 322 -> '18 Nov'."""
    date = datetime.date(2001, 1, 1) + datetime.timedelta(days=round(day_of_year) - 1)
    return f"{date.day} {date:%b}"


def show_value(value, unit):
    """Writes one value with its unit. Day-of-year measures are shown as a calendar date."""
    if pd.isna(value):
        return "no value"
    if unit == "day of year":
        return as_date(value)
    return f"{value:,.1f} {unit}"


def show_change(rate, unit):
    """Writes the change per decade. For a date, that is so many days later or earlier."""
    if pd.isna(rate):
        return "not tested"
    if round(rate, 1) == 0:
        return "no change"
    if unit == "day of year":
        return f"{abs(rate):.1f} days {'later' if rate > 0 else 'earlier'}"
    return f"{rate:+,.1f} {unit}"


st.set_page_config(page_title="Mostly Significant", layout="wide")
st.title("Mostly Significant")
st.write("Everyday weather hunches, fact-checked against 45 years of NASA data.")

results, annual, luck = load_data()

# ---------------------------------------------------------------- THE PICKERS
# The place comes first, because the list of hunches depends on it: UK towns have all
# fifteen, world cities only the five heat hunches that mean the same in any climate.
with st.sidebar:
    st.header("Pick a hunch")
    place = st.selectbox("Where?", results["place"].unique())
    place_rows = results[results["place"] == place].set_index("measure_id")
    choices = [m for m in HUNCHES if m in place_rows.index]
    measure_id = st.selectbox("What's your hunch?", choices, format_func=HUNCHES.get)
    if len(choices) < len(HUNCHES):
        st.caption("World cities are checked on heat only. The season, rain and heating "
                   "hunches are built around UK seasons.")
    st.divider()
    st.caption("Data: NASA POWER (MERRA-2), daily, 1981 to 2025.")

row = place_rows.loc[measure_id]
hunch = HUNCHES[measure_id]
unit = row["unit"]

# ---------------------------------------------------------------- GUESS FIRST
# The visitor commits to a guess before seeing anything, which is what makes the answer
# land. Each place and hunch keeps its own guess, so changing a picker asks again.
st.subheader(f"{place}: “{hunch}”")
guess = st.radio("Before you look at the data, what does your gut say?", GUESSES,
                 index=None, horizontal=True, key=f"guess_{place}_{measure_id}")
if guess is None:
    st.info("Make a guess to see what the data says.")
    st.stop()

# ---------------------------------------------------------------- THE VERDICT
verdict = VERDICTS[row["verdict"]]
verdict["box"](f"**{verdict['label']}.** {verdict['text']}")
st.write(GUT_CHECK.get((guess, row["verdict"]), "Fair enough. That is exactly why it is worth checking."))

# The three numbers behind the verdict: how fast it is changing, the first ten years
# against the last ten, and how often pure luck produced a trend this strong.
first, last = int(row["start_year"]), int(row["end_year"])
luck_rows = luck[(luck["place"] == place) & (luck["measure_id"] == measure_id)]
matched = None if luck_rows.empty else round(luck_rows.iloc[0]["share_as_strong"] * 1000)

col1, col2, col3 = st.columns(3)
col1.metric("Change per decade", show_change(row["rate_per_decade"], unit))
col2.metric(f"{first}–{first + 9} → {last - 9}–{last}",
            f"{show_value(row['early_mean'], unit)} → {show_value(row['late_mean'], unit)}")
if matched is not None:
    col3.metric("Could it be luck?", f"{matched:,} in 1,000")

st.caption(f"**What is measured:** {row['plain_definition']}")
st.caption(f"**Worth knowing:** {row['caveat']}")

if matched is not None and pd.notna(row["p_value"]):
    st.write(
        f"**Could this be luck?** If nothing were changing, the order of the years would not "
        f"matter. So the years were shuffled into a random order 1,000 times. "
        f"**{matched:,}** of those shuffles showed a trend at least as strong as the real one. "
        f"The formal trend test ({row['test_method']}) gives p = {row['p_value']:.3f}; "
        f"under 0.05 counts as a real trend."
    )

# ---------------------------------------------------------------- THE CHART
# Every year's value, with the trend line on top. The line uses the slope from the results
# file and passes through the middle year and the middle value, which is the standard way
# to draw a Sen's slope. Years where the event did not happen have no value and no dot.
yearly = annual[(annual["place"] == place) & (annual["measure_id"] == measure_id)].sort_values("year")
with_value = yearly.dropna(subset=["value"])

fig = go.Figure()
fig.add_trace(go.Scatter(x=yearly["year"], y=yearly["value"], mode="lines+markers", name="Each year"))
if pd.notna(row["rate_per_decade"]) and len(with_value):
    trend = with_value["value"].median() + row["rate_per_decade"] / 10 * (with_value["year"] - with_value["year"].median())
    fig.add_trace(go.Scatter(x=with_value["year"], y=trend, mode="lines", name="Trend", line=dict(width=4)))
fig.update_layout(height=420, xaxis_title="Year", yaxis_title=f"{row['measure_name']} ({unit})",
                  hovermode="x unified", margin=dict(t=20))
st.plotly_chart(fig, width="stretch")

missing = len(yearly) - len(with_value)
if missing:
    st.caption(f"{missing} of {len(yearly)} years have no value, because it did not happen that "
               f"year or the record had not started. Those years are left out of the trend.")

# ---------------------------------------------------------------- THE MAP
# The same hunch in every other place. A UK town shows the twelve UK towns; a world city
# shows every place that has this hunch, on a world view.
world_view = row["region"] == "World"
map_rows = results[results["measure_id"] == measure_id]
if not world_view:
    map_rows = map_rows[map_rows["region"] == "UK"]
map_rows = map_rows.assign(
    Verdict=map_rows["verdict"].map(lambda v: VERDICTS[v]["label"]),
    Change=[show_change(rate, unit) for rate in map_rows["rate_per_decade"]],
)

st.subheader("Same hunch, everywhere else")
counts = map_rows["Verdict"].value_counts()
st.write(f"Across {len(map_rows)} places: "
         + ", ".join(f"**{counts[v['label']]}** {v['label'].lower()}"
                     for v in VERDICTS.values() if v["label"] in counts) + ".")

# The map background follows the app's light or dark theme.
dark = getattr(getattr(st.context, "theme", None), "type", "light") == "dark"
fig_map = px.scatter_map(
    map_rows, lat="lat", lon="lon", color="Verdict",
    color_discrete_map={v["label"]: v["colour"] for v in VERDICTS.values()},
    category_orders={"Verdict": [v["label"] for v in VERDICTS.values()]},
    hover_name="place", hover_data={"Change": True, "Verdict": True, "lat": False, "lon": False},
    labels={"Change": "Change per decade"},
    zoom=0.6 if world_view else 4.3,
    center={"lat": 20, "lon": 10} if world_view else {"lat": 54.5, "lon": -3.0},
    map_style="carto-darkmatter" if dark else "carto-positron", height=550,
)
fig_map.update_traces(marker=dict(size=18))
fig_map.update_layout(margin=dict(l=0, r=0, t=0, b=0))
st.plotly_chart(fig_map, width="stretch")

# ---------------------------------------------------------------- THE SMALL PRINT
# The method and its limits, stated openly for anyone who wants to check the working.
with st.expander("How this works, and what it can't tell you"):
    st.markdown("""
**The data.** NASA POWER (MERRA-2) daily weather from 1 January 1981 to 31 December 2025,
for 12 UK towns and 12 world cities. Each place is one grid square about 50 km across.

**The test.** Each hunch becomes one number per year, such as heatwave days in 1981, 1982
and so on. The Mann-Kendall test asks whether later years beat earlier years more often
than chance would allow. Sen's slope gives the size of the change per decade.

**The four verdicts.**
- **Real trend:** under a 5% chance of being luck, and in the direction the hunch claims.
- **Leaning, not proven:** the right direction, but luck can't be ruled out.
- **Not backed up:** no support in the data.
- **The opposite:** a real trend, going the other way.

**What it can't tell you.**
- Values are averages over a 50 km square, so peaks read low. London's hottest day shows
  about 34.5 °C here; weather stations recorded about 40 °C. The trends are still valid.
- "Unusually hot" is relative to each place: its own hottest 10% of summer days in
  1981–2010. The bar is different in Aberdeen and in Cairo.
- A year with no heatwave or no frost has no date, so it drops out of those trends.
- Belfast, Aberdeen and Toronto use a neighbouring inland square, because their own square
  is mostly sea or lake.
- Rain varies a lot from year to year, so most rain hunches are only "leaning".
- The data shows that something has changed. It does not show why.
""")
